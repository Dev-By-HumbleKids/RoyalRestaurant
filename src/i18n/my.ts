type Tree = Record<string, unknown>;

function withEnglish(base: Dict, source: Dict, paths: readonly string[]): Dict {
  const out: Tree = { ...(base as unknown as Tree) };
  for (const path of paths) {
    const keys = path.split('.');
    let target = out;
    let from = source as unknown as Tree;
    for (const key of keys.slice(0, -1)) {
      target[key] = { ...(target[key] as Tree) };
      target = target[key] as Tree;
      from = from[key] as Tree;
    }
    const last = keys[keys.length - 1];
    if (from?.[last] === undefined) throw new Error(`KEEP_ENGLISH: unknown key "${path}"`);
    target[last] = from[last];
  }
  return out as unknown as Dict;
}

